-- 0008 · Perfiles, proveedores, órdenes de compra y registro de entrega.
-- Los usuarios ya existentes se conservan y se asignan a admin para no
-- bloquear el acceso heredado al instalar la ampliación.
create table profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'consulta' check (role in ('admin', 'almacen', 'compras', 'consulta')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
insert into profiles (user_id, role)
select id, 'admin' from auth.users on conflict (user_id) do nothing;

create function tiene_rol(p_roles text[]) returns boolean
language sql stable security definer set search_path = public as $$
  select auth.uid() is null or exists (select 1 from profiles where user_id = auth.uid() and active and role = any(p_roles));
$$;
revoke all on function tiene_rol(text[]) from public, anon;
grant execute on function tiene_rol(text[]) to authenticated, service_role;

create function crear_perfil_nuevo_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(user_id, role) values (new.id, 'consulta') on conflict do nothing;
  return new;
end $$;
create trigger auth_user_profile after insert on auth.users
for each row execute function crear_perfil_nuevo_usuario();

alter table profiles enable row level security;
create policy "perfil propio o administración" on profiles for select to authenticated
using (user_id = auth.uid() or tiene_rol(array['admin']));
create policy "admin gestiona perfiles" on profiles for all to authenticated
using (tiene_rol(array['admin'])) with check (tiene_rol(array['admin']));
grant select on profiles to authenticated;
grant insert, update on profiles to authenticated;
grant all on profiles to service_role;

