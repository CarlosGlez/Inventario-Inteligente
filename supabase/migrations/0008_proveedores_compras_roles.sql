create table proveedores (
  id bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> '' and char_length(nombre) <= 160),
  correo text not null check (correo ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  telefono text not null default '',
  lead_time_dias integer not null default 7 check (lead_time_dias between 0 and 365),
  minimo_compra numeric(12,2) not null default 0 check (minimo_compra >= 0),
  activo boolean not null default true,
  created_at timestamptz not null default now()
);
create table proveedor_productos (
  proveedor_id bigint not null references proveedores(id) on delete cascade,
  product_id bigint not null references products(id) on delete cascade,
  costo_unitario numeric(12,2) not null default 0 check (costo_unitario >= 0),
  minimo_unidades integer not null default 1 check (minimo_unidades > 0),
  primary key (proveedor_id, product_id)
);
create table ordenes_compra (
  id bigint generated by default as identity primary key,
  folio text not null unique,
  proveedor_id bigint not null references proveedores(id),
  estado text not null default 'borrador' check (estado in ('borrador','enviada','confirmada','recibida parcial','recibida','cancelada')),
  creada_por uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  expected_at timestamptz,
  received_at timestamptz,
  alerta_id bigint references alerts(id) on delete set null
);
create table orden_lineas (
  id bigint generated by default as identity primary key,
  orden_id bigint not null references ordenes_compra(id) on delete cascade,
  product_id bigint not null references products(id),
  cantidad integer not null check (cantidad > 0),
  recibida integer not null default 0 check (recibida >= 0 and recibida <= cantidad),
  costo_unitario numeric(12,2) not null check (costo_unitario >= 0),
  unique (orden_id, product_id)
);

