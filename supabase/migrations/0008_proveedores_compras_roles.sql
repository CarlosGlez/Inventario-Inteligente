-- Crea borradores agrupados por proveedor a partir de la instantánea de alerta.
create function crear_ordenes_desde_alerta(p_alerta_id bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_item jsonb;
  v_proveedor bigint;
  v_orden bigint;
  v_creadas integer := 0;
  v_pid bigint;
  v_cantidad integer;
  v_costo numeric;
  v_lead integer;
  v_linea_id bigint;
  v_minimo numeric;
  v_total numeric;
begin
  if auth.uid() is not null and not tiene_rol(array['admin','compras']) then raise exception 'Permiso denegado.' using errcode = '42501'; end if;
  for v_item in select value from alerts a, jsonb_array_elements(a.items) value where a.id = p_alerta_id
  loop
    v_pid := (v_item->>'id')::bigint;
    select pp.proveedor_id, pp.costo_unitario, pp.minimo_unidades, p.lead_time_dias into v_proveedor, v_costo, v_cantidad, v_lead
    from proveedor_productos pp join proveedores p on p.id = pp.proveedor_id and p.activo
    where pp.product_id = v_pid order by pp.costo_unitario limit 1;
    if v_proveedor is null then continue; end if;
    select id into v_orden from ordenes_compra where alerta_id = p_alerta_id and proveedor_id = v_proveedor and estado = 'borrador' limit 1;
    if v_orden is null then
      insert into ordenes_compra(folio, proveedor_id, creada_por, alerta_id)
      values ('OC-' || to_char(now(),'YYYYMMDD') || '-' || lpad(nextval(pg_get_serial_sequence('ordenes_compra','id'))::text, 6, '0'), v_proveedor, auth.uid(), p_alerta_id)
      returning id into v_orden;
      v_creadas := v_creadas + 1;
    end if;
    -- stock_minimo se usa como stock de seguridad; el lead time está en días.
    v_cantidad := greatest(coalesce((v_item->>'faltante')::integer, 0),
      ceil(coalesce((v_item->>'demanda_diaria_esperada')::numeric, 0) * coalesce(v_lead, 7)
        + coalesce((v_item->>'stock_minimo')::integer, 0) - coalesce((v_item->>'stock_actual')::integer, 0))::integer,
      v_cantidad, coalesce((v_item->>'cantidad_sugerida')::integer, 1));
    insert into orden_lineas(orden_id, product_id, cantidad, costo_unitario)
    values (v_orden, v_pid, v_cantidad, coalesce(v_costo, (v_item->>'costo')::numeric, 0))
    on conflict (orden_id, product_id) do update set cantidad = greatest(orden_lineas.cantidad, excluded.cantidad);
    v_proveedor := null;
  end loop;
  for v_orden in select id from ordenes_compra where alerta_id=p_alerta_id and estado='borrador' loop
    select p.minimo_compra, coalesce(sum(l.cantidad*l.costo_unitario),0)
      into v_minimo, v_total from ordenes_compra o join proveedores p on p.id=o.proveedor_id
      left join orden_lineas l on l.orden_id=o.id where o.id=v_orden group by p.minimo_compra;
    if v_total < v_minimo then
      select id, costo_unitario into v_linea_id, v_costo from orden_lineas
        where orden_id=v_orden and costo_unitario > 0 order by costo_unitario desc limit 1;
      if v_linea_id is null then raise exception 'No se puede cumplir la compra mínima: faltan costos unitarios.'; end if;
      update orden_lineas set cantidad = cantidad + ceil((v_minimo-v_total)/v_costo)::integer where id=v_linea_id;
    end if;
  end loop;
  return v_creadas;
end $$;
grant execute on function crear_ordenes_desde_alerta(bigint) to authenticated, service_role;

-- Recepción parcial o completa actualiza stock con el RPC transaccional existente.
create function recibir_linea_orden(p_linea_id bigint, p_cantidad integer) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_linea orden_lineas;
  v_stock integer;
begin
  if auth.uid() is not null and not tiene_rol(array['admin','almacen']) then raise exception 'Permiso denegado.' using errcode = '42501'; end if;
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'cantidad: debe ser mayor que cero.'; end if;
  select * into v_linea from orden_lineas where id = p_linea_id for update;
  if not found or v_linea.recibida + p_cantidad > v_linea.cantidad then raise exception 'La recepción supera las unidades pendientes.'; end if;
  if exists (select 1 from ordenes_compra where id=v_linea.orden_id and estado='cancelada') then raise exception 'La orden está cancelada.'; end if;
  v_stock := registrar_movimiento((select product_id from orden_lineas where id = p_linea_id), 'entrada', p_cantidad, 'otro');
  update orden_lineas set recibida = recibida + p_cantidad where id = p_linea_id;
  update ordenes_compra o set estado = case when not exists(select 1 from orden_lineas l where l.orden_id=o.id and l.recibida < l.cantidad) then 'recibida' else 'recibida parcial' end,
    received_at = case when not exists(select 1 from orden_lineas l where l.orden_id=o.id and l.recibida < l.cantidad) then now() else null end
    where o.id = v_linea.orden_id;
  return v_stock;
end $$;
grant execute on function recibir_linea_orden(bigint, integer) to authenticated, service_role;

-- Enforce roles at the RPC boundary too. The legacy three-argument signature
-- remains callable and classifies new sales; old rows remain unchanged.
create or replace function registrar_movimiento(p_producto_id bigint, p_tipo text, p_cantidad integer)
returns integer language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not tiene_rol(array['admin','almacen']) then
    raise exception 'Permiso denegado.' using errcode = '42501';
  end if;
  return registrar_movimiento(p_producto_id, p_tipo, p_cantidad, case when p_tipo = 'salida' then 'venta' else 'otro' end);
end $$;

